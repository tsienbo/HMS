-- ============================================================
-- 科室搜索词典：输入科室名、拼音、疾病或症状，找到该挂的科室
-- ------------------------------------------------------------
-- 数据来自开源医疗知识图谱 QASystemOnMedicalKG（8,808 种疾病及其症状、就诊科室），
-- 由 tools/build_dept_keywords.py 整理成 server/data/dept_keywords.csv，
-- 再由 init_db.py 用 COPY 批量导入。本文件可重复执行。
-- ============================================================

-- 三元组索引：加速 term LIKE '%关键词%'。扩展装进单独的 ext 模式，
-- 免得它的几十个函数混进 public，干扰对象清单的统计。
CREATE SCHEMA IF NOT EXISTS ext;
CREATE EXTENSION IF NOT EXISTS pg_trgm SCHEMA ext;

CREATE TABLE IF NOT EXISTS dept_keywords (
  id         INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  term       VARCHAR(60)  NOT NULL,                  -- 搜索词：科室名 / 疾病名 / 症状
  kind       VARCHAR(8)   NOT NULL,                  -- dept / disease / symptom
  dept_id    VARCHAR(8)   REFERENCES departments(id) ON DELETE CASCADE,
  other_dept VARCHAR(20),                            -- 本院未开设的科室（如 妇产科）
  weight     INTEGER      NOT NULL DEFAULT 100,      -- 关联强度：科室名 1000，疾病 100，症状按占比 1~100
  pinyin     VARCHAR(200) NOT NULL DEFAULT '',       -- 全拼，如 weiyan
  abbr       VARCHAR(60)  NOT NULL DEFAULT '',       -- 首字母，如 wy
  CONSTRAINT ck_dk_kind   CHECK (kind IN ('dept', 'disease', 'symptom')),
  -- 一个词要么指向本院科室，要么指向本院未开设的科室，二者恰有其一
  CONSTRAINT ck_dk_target CHECK ((dept_id IS NULL) <> (other_dept IS NULL)),
  CONSTRAINT ck_dk_weight CHECK (weight > 0),
  CONSTRAINT uq_dk_term   UNIQUE NULLS NOT DISTINCT (term, kind, dept_id, other_dept)
);

CREATE INDEX IF NOT EXISTS idx_dk_term_trgm ON dept_keywords USING gin (term ext.gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_dk_pinyin    ON dept_keywords (pinyin text_pattern_ops);  -- 拼音前缀匹配
CREATE INDEX IF NOT EXISTS idx_dk_abbr      ON dept_keywords (abbr   text_pattern_ops);
CREATE INDEX IF NOT EXISTS idx_dk_dept      ON dept_keywords (dept_id);                  -- 外键反查

-- ------------------------------------------------------------
-- fn_search_departments(关键词)：返回匹配的科室，按相关度降序
--   · 中文：词条包含关键词（胃 → 胃炎、胃溃疡），或关键词包含词条（我胃痛 → 胃痛）
--   · 拼音：全拼或首字母前缀（weiyan、wy、neike、nk）
--   · 每条命中按匹配程度打分 × 权重，按科室汇总；得分不到第一名 15% 的科室不返回
--   · 本院未开设的科室也返回（dept_id 为空、other_dept 有值），前端据此给出提示
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_search_departments(p_q TEXT)
RETURNS TABLE (dept_id VARCHAR, other_dept VARCHAR, score NUMERIC, hits TEXT[])
LANGUAGE sql STABLE AS $$
  WITH q AS (
    -- 去空白、转小写；「疼」统一成「痛」（词典入库时做了同样的替换）；
    -- 口语换成医学常用说法：拉肚子 → 腹泻，肚子 → 腹（肚子痛 → 腹痛），嗓子 → 咽（嗓子痛 → 咽痛）
    SELECT replace(replace(replace(
             regexp_replace(lower(regexp_replace(coalesce(p_q, ''), '\s', '', 'g')), '疼(?!痛)', '痛', 'g'),
             '拉肚子', '腹泻'), '肚子', '腹'), '嗓子', '咽') AS q
  ), m AS (
    SELECT k.dept_id, k.other_dept, k.kind, k.term, k.weight,
           CASE
             WHEN k.term = q.q                                        THEN 100
             WHEN q.q ~ '^[a-z]+$' AND (k.pinyin = q.q OR k.abbr = q.q) THEN 80
             WHEN char_length(k.term) >= 2 AND position(k.term IN q.q) > 0 THEN 60
             WHEN k.term LIKE q.q || '%'                                THEN 40
             WHEN q.q ~ '^[a-z]+$'                                      THEN 30
             ELSE 20
           END AS s
      FROM dept_keywords k, q
     WHERE q.q <> ''
       AND char_length(q.q) <= 60
       AND q.q !~ '^[a-z0-9]$'                      -- 单个字母或数字太宽泛，不搜
       AND ( k.term LIKE '%' || q.q || '%'
          OR (char_length(k.term) >= 2 AND position(k.term IN q.q) > 0)
          OR (q.q ~ '^[a-z]+$'
              AND (k.pinyin LIKE q.q || '%' OR k.abbr LIKE q.q || '%')) )
  ), per_term AS (                                 -- 同一个词既是疾病又是症状时只算一次
    SELECT m.dept_id, m.other_dept, m.term, bool_or(m.kind = 'dept') AS is_dept,
           max(m.s * m.weight) AS pts
      FROM m
     GROUP BY m.dept_id, m.other_dept, m.term
  ), agg AS (
    SELECT t.dept_id, t.other_dept,
           round(sum(t.pts) / 100.0, 1) AS score,
           (array_agg(t.term ORDER BY t.pts DESC, char_length(t.term))
              FILTER (WHERE NOT t.is_dept))[1:3] AS hits
      FROM per_term t
     GROUP BY t.dept_id, t.other_dept
  )
  SELECT a.dept_id, a.other_dept, a.score, coalesce(a.hits, '{}')
    FROM agg a
   WHERE a.score >= 0.15 * (SELECT max(score) FROM agg)
   ORDER BY a.score DESC
   LIMIT 8;
$$;
